const fs = require("fs");
const path = require("path");
const Database = require("better-sqlite3");

const dataDir = path.join(__dirname, "data");
if (!fs.existsSync(dataDir)) fs.mkdirSync(dataDir, { recursive: true });

const db = new Database(path.join(dataDir, "app.db"));
db.pragma("journal_mode = WAL");

db.exec(`
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  phone TEXT,
  country TEXT,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  status TEXT NOT NULL DEFAULT 'pending',
  paid INTEGER NOT NULL DEFAULT 0,
  credits INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS testimonials (
  id TEXT PRIMARY KEY,
  name TEXT, city TEXT, text TEXT
);
CREATE TABLE IF NOT EXISTS ticker (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  text TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS slips (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  image_name TEXT,
  fixtures_text TEXT,
  fixtures_json TEXT,
  leans_json TEXT,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS picks (
  id TEXT PRIMARY KEY,
  match TEXT, selection TEXT, odd TEXT, note TEXT, author TEXT,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS payments (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  amount REAL, currency TEXT, type TEXT, status TEXT,
  created_at INTEGER NOT NULL
);
`);

function uid(prefix) {
  return prefix + "_" + Math.random().toString(36).slice(2, 10) + Date.now().toString(36);
}

function getSetting(key, fallback) {
  const row = db.prepare("SELECT v FROM settings WHERE k = ?").get(key);
  if (!row) return fallback;
  try { return JSON.parse(row.v); } catch { return row.v; }
}

function setSetting(key, value) {
  db.prepare("INSERT INTO settings(k,v) VALUES(?,?) ON CONFLICT(k) DO UPDATE SET v=excluded.v")
    .run(key, JSON.stringify(value));
}

